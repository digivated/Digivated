export function aiTopics(project) {
 const entry=reviewed[project.id];
 if(entry)return entry.aiTopics;
 // For new projects, use their primary purpose rather than every incidental keyword.
 const purpose=`${project.name || ''} ${(project.description || '').split(/[.!?]\s/)[0]}`;
 if(project.category!=='AI'&&!/\bAI\b|artificial intelligence|machine learning|LLM|GPT|chatbot/i.test(purpose))return [];
 const primary=aiGroups.find(([name,pattern])=>pattern?.test(purpose));
 return [primary?.[0] || 'Other AI tools'];
}
